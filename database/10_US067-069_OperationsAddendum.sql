-- ===================== pm_parking (ParkingService) =====================

-- US-068: heartbeat & stale data trên ParkingLots
ALTER TABLE "ParkingLots" ADD COLUMN IF NOT EXISTS "LastHeartbeatAtUtc" timestamptz NULL;
ALTER TABLE "ParkingLots" ADD COLUMN IF NOT EXISTS "IsDataStale" boolean NOT NULL DEFAULT false;

-- US-069: emergency stop trên ParkingLots
ALTER TABLE "ParkingLots" ADD COLUMN IF NOT EXISTS "EmergencyStoppedAtUtc" timestamptz NULL;
ALTER TABLE "ParkingLots" ADD COLUMN IF NOT EXISTS "EmergencyStopReason" varchar(500) NULL;

-- US-069: audit log đóng/mở bãi khẩn cấp (EmergencyStopLog)
CREATE TABLE IF NOT EXISTS "EmergencyStopLogs" (
    "Id"          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ParkingLotId" integer NOT NULL,
    "Action"       varchar(500) NOT NULL,   -- "Stop" | "Lift"
    "ActorUserId"  integer NOT NULL,
    "ActorRole"    varchar(500) NULL,
    "Reason"       varchar(500) NOT NULL,
    "AffectedBookings" integer NOT NULL,
    "CreatedAtUtc" timestamptz NOT NULL,
    "UpdatedAtUtc" timestamptz NULL
);
CREATE INDEX IF NOT EXISTS "IX_EmergencyStopLogs_ParkingLotId"
    ON "EmergencyStopLogs" ("ParkingLotId");

-- ===================== pm_gate (GateService) =====================

-- US-069: cache trạng thái emergency stop (consumer LotEmergencyStopped/Lifted)
CREATE TABLE IF NOT EXISTS "LotOperationalStatuses" (
    "Id"           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ParkingLotId" integer NOT NULL,
    "IsClosed"     boolean NOT NULL,
    "ClosedReason" varchar(500) NULL,
    "ClosedAtUtc"  timestamptz NULL,
    "CreatedAtUtc" timestamptz NOT NULL,
    "UpdatedAtUtc" timestamptz NULL
);
-- 1 row / lot (consumer dùng SingleOrDefaultAsync theo ParkingLotId)
CREATE UNIQUE INDEX IF NOT EXISTS "IX_LotOperationalStatuses_ParkingLotId"
    ON "LotOperationalStatuses" ("ParkingLotId");

-- US-069: inbox idempotency cho consumer (TransactionalInbox.ApplyOnceAsync)
CREATE TABLE IF NOT EXISTS "InboxReceipts" (
    "EventId"        uuid PRIMARY KEY,
    "ProcessedAtUtc" timestamptz NOT NULL
);

